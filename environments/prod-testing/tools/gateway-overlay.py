#!/usr/bin/env python3
"""Generate a values overlay that moves every Istio gateway reference in an oan-helm chart's
values.yaml from FROM (default istio-system/development) to TO (default test/internal).

The oan-helm charts pass `istio.virtualservice.gateway` through untouched (no tpl), so it cannot
follow a global; each key has to be set. Dict keys are overridden individually. A list that
contains a gateway is emitted WHOLE (Helm replaces lists), with only the gateway values changed.

usage: gateway-overlay.py <values.yaml> [FROM] [TO] > overlay.yaml
"""
import sys, yaml

src = sys.argv[1]
FROM = sys.argv[2] if len(sys.argv) > 2 else "istio-system/development"
TO = sys.argv[3] if len(sys.argv) > 3 else "test/internal"

def contains(o):
    if isinstance(o, dict): return any(contains(v) for v in o.values())
    if isinstance(o, list): return any(contains(v) for v in o)
    return o == FROM

def replaced(o):
    if isinstance(o, dict): return {k: replaced(v) for k, v in o.items()}
    if isinstance(o, list): return [replaced(v) for v in o]
    return TO if o == FROM else o

def overlay(o):
    """Minimal dict carrying only the paths that lead to FROM; lists copied whole."""
    out = {}
    for k, v in o.items():
        if isinstance(v, dict):
            sub = overlay(v)
            if sub: out[k] = sub
        elif isinstance(v, list):
            if contains(v): out[k] = replaced(v)
        elif v == FROM:
            out[k] = TO
    return out

def count(o):
    if isinstance(o, dict): return sum(count(v) for v in o.values())
    if isinstance(o, list): return sum(count(v) for v in o)
    return 1 if o == TO else 0

ov = overlay(yaml.safe_load(open(src)))
print(f"# GENERATED by values/tools/gateway-overlay.py from {src.split('/')[-2] if '/' in src else src}")
print(f"# {FROM} -> {TO}: {count(ov)} gateway keys. Lists are copied whole (Helm replaces lists).")
print(yaml.safe_dump(ov, sort_keys=False, width=200, allow_unicode=True), end="")
